
import sqlite3
from datetime import datetime, timezone
from time import monotonic

from .connection import get_connection
from .models import Scan
from .file_repo import save_files_batch

def create_scan(scan_path: str) -> int:
    """
    Create a new directory scan record in the Scans table.

    The scan's starting timestamp is automatically recorded in UTC.
    SQLite generates a unique scan_id, and the remaining fields
    use their default values until the scan is updated.

    Args:
        scan_path (str): Path of the directory being scanned.

    Returns:
        int: The unique scan_id generated by SQLite.

    Raises:
        TypeError: If scan_path is not a string.
        ValueError: If scan_path is empty or contains only whitespace.
        sqlite3.Error: If a database operation fails.
    """

    # Validate the directory path before saving it.
    if not isinstance(scan_path, str):
        raise TypeError("scan_path must be a string.")

    if not scan_path.strip():
        raise ValueError("scan_path cannot be empty.")

    # Store the scan's starting time in UTC.
    scan_timestamp = datetime.now(timezone.utc).isoformat()

    connection = get_connection()

    try:
        # SQLite automatically generates the scan_id.
        cursor = connection.execute(
            """
            INSERT INTO Scans (scan_path, scan_timestamp)
            VALUES (?, ?)
            """,
            (scan_path, scan_timestamp)
        )

        scan_id = cursor.lastrowid

        if scan_id is None:
            raise sqlite3.DatabaseError("Failed to retrieve the new scan ID.")

        connection.commit()
        return scan_id

    except sqlite3.Error:
        connection.rollback()
        raise

    finally:
        connection.close()


def update_scan(
    scan_id: int,
    file_count: int,
    total_size: int,
    scan_duration: int,
    status: str
) -> None:
    """
    Update an existing scan with its statistics and status.

    Args:
        scan_id (int): Unique ID of the scan to update.
        file_count (int): Number of files discovered during the scan.
        total_size (int): Total size of discovered files in bytes.
        scan_duration (int): Duration of the scan in seconds.
        status (str): Scan status, which must be "incomplete",
            "completed", or "failed".

    Returns:
        None: Updates the scan record without returning a value.

    Raises:
        TypeError: If scan_id, file_count, total_size, or
            scan_duration has an invalid type, or status is not a string.
        ValueError: If numeric values are negative, scan_id is
            not positive, or status is invalid.
        LookupError: If no scan exists with the supplied scan_id.
        sqlite3.Error: If a database operation fails.
    """

    # Reject invalid IDs and negative statistics.
    if type(scan_id) is not int:
        raise TypeError("scan_id must be an integer.")

    if scan_id <= 0:
        raise ValueError("scan_id must be positive.")

    for name, value in {
        "file_count": file_count,
        "total_size": total_size,
        "scan_duration": scan_duration
    }.items():
        if type(value) is not int:
            raise TypeError(f"{name} must be an integer.")

        if value < 0:
            raise ValueError(f"{name} cannot be negative.")

    if not isinstance(status, str):
        raise TypeError("status must be a string.")

    if status not in {"incomplete", "completed", "failed"}:
        raise ValueError("Invalid scan status.")

    connection = get_connection()

    try:
        # Update only the scan matching the supplied scan_id.
        cursor = connection.execute(
            """
            UPDATE Scans
            SET file_count = ?,
                total_size = ?,
                scan_duration = ?,
                status = ?
            WHERE scan_id = ?
            """,
            (file_count, total_size, scan_duration, status, scan_id)
        )

        if cursor.rowcount == 0:
            raise LookupError(f"Scan with ID {scan_id} does not exist.")

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


def get_scan(scan_id: int) -> Scan | None:
    """
    Retrieve a scan record by its unique ID.

    Args:
        scan_id (int): Unique ID of the scan to retrieve.

    Returns:
        Scan | None: A Scan dataclass object containing the scan's
            information, or None if the scan does not exist.

    Raises:
        TypeError: If scan_id is not an integer.
        ValueError: If scan_id is not positive.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int:
        raise TypeError("scan_id must be an integer.")

    if scan_id <= 0:
        raise ValueError("scan_id must be positive.")

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT *
            FROM Scans
            WHERE scan_id = ?
            """,
            (scan_id,)
        )

        row = cursor.fetchone()

        if row is None:
            return None

        # Convert the SQLite row into our Scan dataclass.
        return Scan(**dict(row))

    finally:
        connection.close()


def list_scans() -> list[Scan]:
    """
    Retrieve all scan records from the Scans table.

    Scans are ordered from newest to oldest using their
    timestamps, with scan_id as a secondary ordering field.

    Args:
        None.

    Returns:
        list[Scan]: A list of Scan dataclass objects.
            Returns an empty list if no scans exist.

    Raises:
        sqlite3.Error: If a database operation fails.
    """

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT *
            FROM Scans
            ORDER BY scan_timestamp DESC, scan_id DESC
            """
        )

        # Convert every database row into a Scan object.
        return [Scan(**dict(row)) for row in cursor.fetchall()]

    finally:
        connection.close()


def save_scan_results(
    scan_path: str,
    file_data_list: list[dict]
) -> int:
    """
    Save successfully processed file metadata and finalize a scan.

    Inaccessible files are skipped and are not stored in the database.
    Accessible files are saved in one batch transaction.

    If the batch insertion fails, its changes are rolled back and
    the scan is marked as failed.

    Args:
        scan_path (str): Directory path associated with the scan.
        file_data_list (list[dict]): Metadata dictionaries produced
            by the scanner. Each dictionary must contain the fields
            required by save_files_batch().

    Returns:
        int: The unique ID of the newly created scan.

    Raises:
        TypeError: If file_data_list is not a list or contains
            non-dictionary elements.
        ValueError: If scan_path or file metadata is invalid.
        sqlite3.Error: If a database operation fails.
    """

    # Validate the collection before creating a scan record.
    if not isinstance(file_data_list, list):
        raise TypeError("file_data_list must be a list.")

    # Start measuring the time spent saving the scan results.
    start_time = monotonic()

    # Create a scan record with the default status "incomplete".
    scan_id = create_scan(scan_path)

    file_count = 0
    total_size = 0

    try:
        accessible_files = []

        # Examine each metadata dictionary returned by the scanner.
        for file_data in file_data_list:

            if not isinstance(file_data, dict):
                raise TypeError(
                    "Each file metadata item must be a dictionary."
                )

            # Skip files that the scanner could not access.
            # Their metadata and error details are not stored.
            if file_data.get("accessible") is not True:
                continue

            # Attach the scan ID without changing the original
            # dictionary provided by the scanner.
            prepared_file = {
                **file_data,
                "scan_id": scan_id
            }

            accessible_files.append(prepared_file)

        # Insert all accessible files using one connection and
        # transaction. A failed insertion rolls back the batch.
        save_files_batch(accessible_files)

        # Count only the files successfully saved in this batch.
        file_count = len(accessible_files)

        # Calculate total storage from successfully saved files.
        # Treat a missing file size (None) as zero bytes.
        total_size = sum(
            file_data["size"] or 0
            for file_data in accessible_files
        )

        # Calculate elapsed time in whole seconds.
        duration = int(monotonic() - start_time)

        # Finalize the metadata-saving operation successfully.
        update_scan(
            scan_id=scan_id,
            file_count=file_count,
            total_size=total_size,
            scan_duration=duration,
            status="completed"
        )

        return scan_id

    except Exception:
        # Calculate elapsed time even if an operation fails.
        duration = int(monotonic() - start_time)

        try:
            # Mark the scan as failed so it is not mistaken
            # for a successfully completed operation.
            update_scan(
                scan_id=scan_id,
                file_count=file_count,
                total_size=total_size,
                scan_duration=duration,
                status="failed"
            )

        except Exception:
            # Preserve the original exception if updating the
            # scan status also fails. In that situation, the
            # scan may remain marked as incomplete.
            pass

        # Re-raise the original error for the calling program.
        raise
