
import sqlite3

from .connection import get_connection
from .models import FileMetadata, FileHash



def save_file_metadata(file_data: dict) -> int:
    """
    Save a file's metadata to the Files table.

    Args:
        file_data (dict): Dictionary containing the file's metadata.
            Required fields:
                scan_id (int): ID of the scan the file belongs to.
                path (str): Full path of the file.
                name (str): Name of the file.

            Optional fields:
                size (int | None): File size in bytes.
                extension (str): File extension.
                category (str): File category (defaults to "Other").
                created (str): File creation timestamp.
                modified (str): Last modification timestamp.
                accessed_timestamp (str): Last access timestamp.
                accessible (bool): Whether file metadata was accessible
                    (defaults to True).
                error (str): Error message if metadata access failed.

    Returns:
        int: The unique file_id generated by SQLite.

    Raises:
        TypeError: If file_data is not a dictionary or accessible
            is not a boolean.
        ValueError: If required fields are missing, scan_id is invalid,
            path or name is empty, size is invalid, or category is invalid.
        sqlite3.Error: If a database operation fails.
    """

    # Ensure that the provided metadata is a dictionary.
    if not isinstance(file_data, dict):
        raise TypeError("file_data must be a dictionary.")

    # These fields are required to identify and store a file.
    required_fields = ("scan_id", "path", "name")

    for field in required_fields:
        if field not in file_data:
            raise ValueError(f"Missing required field: {field}")

    # Extract the required metadata from the dictionary.
    scan_id = file_data["scan_id"]
    path = file_data["path"]
    name = file_data["name"]

    # Size may be None if the scanner cannot access the file.
    size = file_data.get("size")

    # Ensure the scan ID is a positive integer.
    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    # Ensure the file path is a non-empty string.
    if not isinstance(path, str) or not path.strip():
        raise ValueError("path must be a non-empty string.")

    # Ensure the file name is a non-empty string.
    if not isinstance(name, str) or not name.strip():
        raise ValueError("name must be a non-empty string.")

    # A file's size must be non-negative, unless it is unknown.
    if size is not None:
        if type(size) is not int or size < 0:
            raise ValueError("size must be a non-negative integer or None.")

    # The scanner provides a boolean indicating whether
    # file metadata could be accessed successfully.
    accessible = file_data.get("accessible", True)

    if type(accessible) is not bool:
        raise TypeError("accessible must be a boolean.")

    # Use "Other" if the scanner does not provide a category.
    category = file_data.get("category", "Other")

    # Ensure that the category is a non-empty string.
    if not isinstance(category, str) or not category.strip():
        raise ValueError("category must be a non-empty string.")

    # Establish a connection to the SQLite database.
    connection = get_connection()

    try:
        # Parameter placeholders (?) keep values separate
        # from SQL syntax and prevent SQL injection.
        #
        # The column names match the scanner's metadata keys.
        cursor = connection.execute(
            """
            INSERT INTO Files (
                scan_id,
                path,
                name,
                size,
                extension,
                category,
                created,
                modified,
                accessed_timestamp,
                accessible,
                error
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                scan_id,
                path,
                name,
                size,
                file_data.get("extension"),
                category,
                file_data.get("created"),
                file_data.get("modified"),

                # The scanner does not currently provide
                # an accessed timestamp.
                file_data.get("accessed_timestamp"),

                # SQLite stores booleans as integers (1 or 0).
                int(accessible),

                # Store any error reported by the scanner.
                file_data.get("error")
            )
        )

        # Retrieve the unique ID assigned to the inserted file.
        file_id = cursor.lastrowid

        # Ensure SQLite successfully generated a file ID.
        if file_id is None:
            raise sqlite3.DatabaseError(
                "Failed to retrieve the new file ID."
            )

        # Permanently save the insertion to the database.
        connection.commit()

        # Return the ID so other tables can reference this file.
        return file_id

    except sqlite3.Error:
        # Undo the insertion if a database operation fails.
        connection.rollback()
        raise

    finally:
        # Always close the connection, even if an error occurs.
        connection.close()



def save_file_hash(
    file_id: int,
    hash_value: str,
    hash_algorithm: str
) -> int:
    """
    Save a file's calculated hash in the FileHashes table.

    Args:
        file_id (int): Unique ID of the file whose hash is being stored.
        hash_value (str): Calculated hash value of the file.
        hash_algorithm (str): Name of the hashing algorithm used,
            such as "sha256".

    Returns:
        int: The unique hash_id generated by SQLite.

    Raises:
        ValueError: If file_id is not a positive integer, or
            hash_value or hash_algorithm is empty or invalid.
        sqlite3.Error: If a database operation fails, including
            foreign key or uniqueness constraint violations.
    """

    if type(file_id) is not int or file_id <= 0:
        raise ValueError("file_id must be a positive integer.")

    if not isinstance(hash_value, str) or not hash_value.strip():
        raise ValueError("hash_value must be a non-empty string.")

    if not isinstance(hash_algorithm, str) or not hash_algorithm.strip():
        raise ValueError("hash_algorithm must be a non-empty string.")

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            INSERT INTO FileHashes (
                file_id,
                hash_value,
                hash_algorithm
            )
            VALUES (?, ?, ?)
            """,
            (file_id, hash_value, hash_algorithm)
        )

        hash_id = cursor.lastrowid

        if hash_id is None:
            raise sqlite3.DatabaseError("Failed to retrieve the new hash ID.")

        connection.commit()
        return hash_id

    except sqlite3.Error:
        connection.rollback()
        raise

    finally:
        connection.close()


def get_files_by_scan(scan_id: int) -> list[FileMetadata]:
    """
    Retrieve all files belonging to a particular scan.

    Files are returned in ascending order of their paths.

    Args:
        scan_id (int): Unique ID of the scan whose files
            should be retrieved.

    Returns:
        list[FileMetadata]: A list of FileMetadata objects
            representing the files belonging to the scan.
            Returns an empty list if no matching files exist.

    Raises:
        ValueError: If scan_id is not a positive integer.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT *
            FROM Files
            WHERE scan_id = ?
            ORDER BY path
            """,
            (scan_id,)
        )

        # Convert SQLite rows into FileMetadata objects.
        return [
            _row_to_file_metadata(row)
            for row in cursor.fetchall()
        ]

    finally:
        connection.close()


def get_files_by_extension(
    scan_id: int,
    extension: str
) -> list[FileMetadata]:
    """
    Retrieve files with a specific extension from a scan.

    The extension comparison is case-insensitive.
    Both "pdf" and ".pdf" are accepted.

    Args:
        scan_id (int): Unique ID of the scan to search.
        extension (str): File extension to filter by,
            such as ".pdf" or "pdf".

    Returns:
        list[FileMetadata]: A list of FileMetadata objects
            matching the specified extension, ordered by path.
            Returns an empty list if no matching files exist.

    Raises:
        ValueError: If scan_id is not a positive integer,
            or extension is empty or invalid.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    if not isinstance(extension, str) or not extension.strip():
        raise ValueError("extension must be a non-empty string.")

    # Accept both "pdf" and ".pdf" as input.
    extension = extension.strip().lower()

    if not extension.startswith("."):
        extension = "." + extension

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT *
            FROM Files
            WHERE scan_id = ?
            AND LOWER(extension) = ?
            ORDER BY path
            """,
            (scan_id, extension)
        )

        return [
            _row_to_file_metadata(row)
            for row in cursor.fetchall()
        ]

    finally:
        connection.close()


def get_largest_files(
    scan_id: int,
    limit: int = 10
) -> list[FileMetadata]:
    """
    Retrieve the largest files belonging to a particular scan.

    Files are ordered by size in descending order.
    Files with unknown sizes (NULL) are excluded.

    Args:
        scan_id (int): Unique ID of the scan to search.
        limit (int): Maximum number of files to retrieve.
            Defaults to 10.

    Returns:
        list[FileMetadata]: A list of FileMetadata objects
            ordered from largest to smallest.
            Returns an empty list if no matching files exist.

    Raises:
        ValueError: If scan_id or limit is not a positive integer.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    if type(limit) is not int or limit <= 0:
        raise ValueError("limit must be a positive integer.")

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT *
            FROM Files
            WHERE scan_id = ?
            AND size IS NOT NULL
            ORDER BY size DESC, file_id ASC
            LIMIT ?
            """,
            (scan_id, limit)
        )

        return [
            _row_to_file_metadata(row)
            for row in cursor.fetchall()
        ]

    finally:
        connection.close()


def get_total_storage(scan_id: int) -> int:
    """
    Calculate the total storage used by files in a scan.

    The total is calculated by summing the sizes of all files
    belonging to the specified scan. Unknown sizes are ignored.

    Args:
        scan_id (int): Unique ID of the scan whose total
            storage usage should be calculated.

    Returns:
        int: Total storage used by the scan's files, in bytes.
            Returns 0 if no files have known sizes.

    Raises:
        ValueError: If scan_id is not a positive integer.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    connection = get_connection()

    try:
        cursor = connection.execute(
            """
            SELECT COALESCE(SUM(size), 0) AS total_storage
            FROM Files
            WHERE scan_id = ?
            """,
            (scan_id,)
        )

        row = cursor.fetchone()
        return row["total_storage"]

    finally:
        connection.close()


def _row_to_file_metadata(row: sqlite3.Row) -> FileMetadata:
    """
    Convert a SQLite Files table row into a FileMetadata object.

    The row is converted into a dictionary so its column
    names can be used as FileMetadata constructor arguments.
    SQLite stores booleans as integers, so the accessible
    field is converted back into a Python boolean.

    Args:
        row (sqlite3.Row): Database row containing the
            metadata of a single file.

    Returns:
        FileMetadata: A FileMetadata dataclass instance
            containing the file's information.

    Raises:
        KeyError: If the required accessible column is missing.
        TypeError: If the row cannot be converted into a
            dictionary or its fields do not match FileMetadata.
    """

    data = dict(row)
    data["accessible"] = bool(data["accessible"])

    return FileMetadata(**data)
