def create_duplicate_group(
    scan_id: int,
    hash_value: str,
    duplicate_count: int,
    potential_savings: int,
    connection: sqlite3.Connection | None = None,
) -> int:
    """
    Create a new duplicate group in the DuplicateGroups table.

    Args:
        hash_value (str): Hash shared by files with identical contents.
        duplicate_count (int): Number of files in the duplicate group.
            Must be at least 2.
        potential_savings (int): Storage space that could potentially
            be recovered by removing redundant copies, in bytes.
        scan_id (int): Unique ID of the scan that owns this duplicate group.
            Must be a positive integer.
        connection (sqlite3.Connection | None): Optional existing database
            connection. The caller manages its transaction if provided.

    Returns:
        int: The unique group_id generated by SQLite.

    Raises:
        ValueError: If any input value is invalid.
        sqlite3.Error: If a database operation fails.
    """

    # Validate inputs before performing database operations.
    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    if not isinstance(hash_value, str) or not hash_value.strip():
        raise ValueError("hash_value must be a non-empty string.")

    if type(duplicate_count) is not int or duplicate_count < 2:
        raise ValueError("duplicate_count must be an integer of at least 2.")

    if type(potential_savings) is not int or potential_savings < 0:
        raise ValueError("potential_savings must be a non-negative integer.")

    # Create a connection only if the caller has not supplied one.
    owns_connection = connection is None

    if owns_connection:
        connection = get_connection()

    try:
        # Store the duplicate group's hash and summary statistics.
        cursor = connection.execute(
            """
            INSERT INTO DuplicateGroups (
                scan_id,
                hash_value,
                duplicate_count,
                potential_savings
            )
            VALUES (?, ?, ?, ?)
            """,
            (scan_id, hash_value, duplicate_count, potential_savings),
        )

        group_id = cursor.lastrowid

        if group_id is None:
            raise sqlite3.DatabaseError(
                "Failed to retrieve the new duplicate group ID."
            )

        # Commit only when this function owns the connection.
        if owns_connection:
            connection.commit()

        return group_id

    except sqlite3.Error:
        # Leave rollback to the caller when using a shared connection.
        if owns_connection:
            connection.rollback()
        raise

    finally:
        # Close only connections created by this function.
        if owns_connection:
            connection.close()





def add_duplicate_member(
    group_id: int,
    file_id: int,
    is_primary: bool = False,
    connection: sqlite3.Connection | None = None,
) -> None:
    """
    Associate an existing file with a duplicate group.

    The file and duplicate group must belong to the same scan.
    The is_primary flag identifies a representative file, not
    necessarily the original file.

    Args:
        group_id (int): Unique ID of the duplicate group.
        file_id (int): Unique ID of the file to add.
        is_primary (bool): Whether the file is the representative
            member of the group. Defaults to False.
        connection (sqlite3.Connection | None): Optional existing database
            connection. The caller manages its transaction if provided.

    Returns:
        None: Inserts the membership without returning a value.

    Raises:
        ValueError: If IDs are invalid or the file and duplicate
            group belong to different scans.
        TypeError: If is_primary is not a boolean.
        sqlite3.Error: If a database operation fails.
    """

    # Validate IDs before performing database operations.
    if type(group_id) is not int or group_id <= 0:
        raise ValueError("group_id must be a positive integer.")

    if type(file_id) is not int or file_id <= 0:
        raise ValueError("file_id must be a positive integer.")

    if type(is_primary) is not bool:
        raise TypeError("is_primary must be a boolean.")

    # Create a connection only if one was not provided.
    owns_connection = connection is None

    if owns_connection:
        connection = get_connection()

    try:
        # Check that the file and duplicate group belong to the same scan.
        ownership = connection.execute(
            """
            SELECT 1
            FROM DuplicateGroups AS dg
            JOIN Files AS f
                ON dg.scan_id = f.scan_id
            WHERE dg.group_id = ?
              AND f.file_id = ?
            """,
            (group_id, file_id),
        ).fetchone()

        if ownership is None:
            # Check whether both records exist before reporting a mismatch.
            group_exists = connection.execute(
                "SELECT 1 FROM DuplicateGroups WHERE group_id = ?",
                (group_id,),
            ).fetchone()

            file_exists = connection.execute(
                "SELECT 1 FROM Files WHERE file_id = ?",
                (file_id,),
            ).fetchone()

            if group_exists is not None and file_exists is not None:
                raise ValueError(
                    "The file and duplicate group must belong to the same scan."
                )

            raise sqlite3.IntegrityError(
                "The duplicate group or file does not exist."
            )

        # Insert the file as a member of the duplicate group.
        connection.execute(
            """
            INSERT INTO DuplicateMembers (
                group_id,
                file_id,
                is_primary
            )
            VALUES (?, ?, ?)
            """,
            (group_id, file_id, int(is_primary)),
        )

        # Commit only when this function owns the connection.
        if owns_connection:
            connection.commit()

    except (sqlite3.Error, ValueError):
        # Leave rollback to the caller when using a shared connection.
        if owns_connection:
            connection.rollback()
        raise

    finally:
        # Close only connections created by this function.
        if owns_connection:
            connection.close()




def get_duplicate_groups(scan_id: int) -> list[DuplicateGroup]:
    """
    Retrieve all duplicate groups belonging to a given scan.

    DuplicateGroups stores scan_id directly, so no joins are
    required to identify the groups belonging to a scan.

    Results are ordered by potential savings in descending order,
    with group_id used to break ties.

    Args:
        scan_id (int): Unique ID of the scan whose duplicate
            groups should be retrieved.

    Returns:
        list[DuplicateGroup]: DuplicateGroup objects containing
            the hash, duplicate count, and potential savings.
            Returns an empty list if no matching groups exist.

    Raises:
        ValueError: If scan_id is not a positive integer.
        sqlite3.Error: If a database operation fails.
    """

    if type(scan_id) is not int or scan_id <= 0:
        raise ValueError("scan_id must be a positive integer.")

    connection = get_connection()

    try:
        # Filter groups directly by their owning scan.
        # No joins are needed because DuplicateGroups stores scan_id.
        cursor = connection.execute(
            """
            SELECT *
            FROM DuplicateGroups
            WHERE scan_id = ?
            ORDER BY potential_savings DESC, group_id ASC
            """,
            (scan_id,),
        )

        return [
            DuplicateGroup(**dict(row))
            for row in cursor.fetchall()
        ]

    finally:
        connection.close()


def get_duplicate_members(group_id: int) -> list[FileMetadata]:
    """
    Retrieve all files belonging to a duplicate group.

    The files are returned with the representative member first,
    followed by the remaining files ordered alphabetically by path.

    Args:
        group_id (int): Unique ID of the duplicate group.

    Returns:
        list[FileMetadata]: FileMetadata objects representing
            the files belonging to the group.
            Returns an empty list if the group has no members.

    Raises:
        ValueError: If group_id is not a positive integer.
        sqlite3.Error: If a database operation fails.
    """

    if type(group_id) is not int or group_id <= 0:
        raise ValueError("group_id must be a positive integer.")

    connection = get_connection()

    try:
        # Join the membership table with Files to retrieve
        # the complete metadata of each duplicate file.
        cursor = connection.execute(
            """
            SELECT f.*
            FROM Files AS f
            JOIN DuplicateMembers AS dm
                ON f.file_id = dm.file_id
            WHERE dm.group_id = ?
            ORDER BY dm.is_primary DESC, f.path ASC
            """,
            (group_id,)
        )

        return [
            _row_to_file_metadata(row)
            for row in cursor.fetchall()
        ]

    finally:
        connection.close()
